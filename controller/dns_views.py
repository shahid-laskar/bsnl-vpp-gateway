"""Per-subscriber DNS view membership in Unbound (P5-T5, ADR-014).

The static resolver config maps every tenant subnet to the ``captive`` view.
This module keeps one generated include file that maps each *authenticated*
subscriber's /32 to the ``authenticated`` view (longest prefix wins) and tells
Unbound to reload it.

Unbound 1.19 has no runtime command to change ``access-control-view``, so the
file is rewritten and ``unbound-control reload_keep_cache`` is issued. Before
the reload the whole configuration is checked with ``unbound-checkconf``; a
failing check restores the previous file and skips the reload (a bad config
would stop Unbound on reload).

Failure direction: if a sync fails, a newly authenticated subscriber keeps
captive DNS answers (the OS keeps showing the portal) and a deactivated one
keeps normal recursion until the next successful sync. DNS is not the
enforcement point; the VPP tenant ACL is.
"""
from __future__ import annotations

import ipaddress
import logging
import os
import subprocess
import tempfile
import threading
from pathlib import Path
from typing import Any, Callable, Sequence

from .host_services import AUTHENTICATED_VIEW

LOG = logging.getLogger("bsnl_vpp.dns_views")
ACTIVE_STATE = "authenticated"
HEADER = "# Generated by bsnl-vpp-controller (controller/dns_views.py). Do not edit.\n"


def authenticated_addresses(state: dict[str, Any]) -> list[str]:
    """Sorted IPv4 addresses of authenticated subscribers of enabled tenants."""
    enabled = {t["tenant_key"] for t in state.get("tenants") or [] if t.get("admin_state", "enabled") == "enabled"}
    addresses = set()
    for item in state.get("subscribers") or []:
        if item.get("state") == ACTIVE_STATE and item.get("tenant_key") in enabled:
            addresses.add(ipaddress.IPv4Address(item["private_ipv4"]))
    return [str(a) for a in sorted(addresses)]


def render_views(state: dict[str, Any]) -> str:
    lines = [HEADER.rstrip("\n"), "server:"]
    for address in authenticated_addresses(state):
        lines += [f"  access-control: {address}/32 allow", f"  access-control-view: {address}/32 {AUTHENTICATED_VIEW}"]
    return "\n".join(lines) + "\n"


def _run(command: Sequence[str]) -> None:
    subprocess.run(list(command), check=True, capture_output=True, text=True, timeout=30)


class UnboundViewSync:
    def __init__(self, path: str | Path, *, checkconf: Sequence[str] = ("unbound-checkconf",),
                 reload: Sequence[str] = ("unbound-control", "reload_keep_cache"),
                 runner: Callable[[Sequence[str]], None] = _run) -> None:
        self.path = Path(path)
        self.checkconf, self.reload, self.runner = tuple(checkconf), tuple(reload), runner
        self._lock = threading.Lock()
        self._applied: str | None = None  # content Unbound has successfully loaded
        self.last_error: str | None = None

    def sync(self, state: dict[str, Any]) -> bool:
        """Make Unbound's authenticated view match ``state``. True if reloaded."""
        content = render_views(state)
        with self._lock:
            if content == self._applied:
                return False
            previous = self.path.read_text(encoding="utf-8") if self.path.exists() else None
            try:
                self._write(content)
                try:
                    self.runner(self.checkconf)
                except Exception:
                    if previous is None:
                        self.path.unlink(missing_ok=True)
                    else:
                        self._write(previous)
                    raise
                self.runner(self.reload)
            except Exception as exc:
                detail = getattr(exc, "stderr", "") or ""
                self.last_error = f"{type(exc).__name__}: {exc} {detail}".strip()
                LOG.error("DNS view sync failed (will retry): %s", self.last_error)
                return False
            self._applied, self.last_error = content, None
            LOG.info("DNS views reloaded: %d authenticated subscriber(s)", content.count("access-control-view"))
            return True

    def _write(self, content: str) -> None:
        """Atomic replace, mode 0644.

        World-readable on purpose: Unbound reads its config as root before
        dropping privileges, and its AppArmor profile grants no
        dac_override, so root cannot read a 0640 file it neither owns nor
        shares a group with (the service then fails to start).
        """
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile("w", dir=self.path.parent, prefix=f".{self.path.name}.", delete=False, encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
            temporary = Path(handle.name)
        os.chmod(temporary, 0o644)
        temporary.replace(self.path)
